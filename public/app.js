/* RadioRang — One Station, Any Vibe
 * Client: WebSocket relay + Web Audio API sync engine.
 *
 * Sync model (unchanged): the server owns the playback clock
 * (startedAtEpochMs). Each client calibrates its clock offset (ping/pong RTT
 * via lib/sync/clock.ts estimateOffset), then schedules the shared track with
 * AudioContext at the exact target time (elapsedAt). Reconnects re-seek to
 * the server timeline; a Service Worker caches the audio so playback survives
 * dropped networks.
 *
 * Deployment: the app can run same-origin (Node server serves everything) or
 * split (static frontend on Vercel + realtime server elsewhere). The realtime
 * server's base URL is injected at build time by scripts/gen-config.js into
 * /rr-config.js (window.RR_CONFIG). Empty values mean "same origin".
 */
'use strict';

import { estimateOffset, elapsedAt } from '/lib/sync/clock.js';
import { AZAADI } from '/data/azaadi.js';

const $ = (sel) => document.querySelector(sel);
const $$ = (sel) => [...document.querySelectorAll(sel)];

/* ---------------------------------------------------------------- *
 *  Deployment config (see /rr-config.js, generated by gen-config.js)
 * ---------------------------------------------------------------- */
const RR_CONFIG = window.RR_CONFIG || {};
const API_BASE = RR_CONFIG.apiBase || '';   // e.g. 'https://rr-api.example.com'
const WS_BASE = RR_CONFIG.wsBase || '';     // e.g. 'wss://rr-api.example.com'
const api = (path) => API_BASE + path;

function wsUrl(code) {
  const base = WS_BASE || `${location.protocol === 'https:' ? 'wss' : 'ws'}://${location.host}`;
  return `${base}/ws?code=${encodeURIComponent(code)}&name=${encodeURIComponent(myName)}`;
}

/* ---------------------------------------------------------------- *
 *  Tiny router: #home | #station, with /station/<code> URLs
 * ---------------------------------------------------------------- */
function show(view) {
  $$('.view').forEach((v) => v.classList.toggle('hidden', v.id !== 'view-' + view));
}

const CODE_RE = /^[A-Z0-9]{6}$/;

function codeFromPath() {
  const m = location.pathname.match(/^\/station\/([A-Za-z0-9]{6})$/);
  return m ? m[1].toUpperCase() : null;
}

/* ---------------------------------------------------------------- *
 *  App state
 * ---------------------------------------------------------------- */
let station = null;       // latest publicState from server
let myId = null;
let myName = localStorage.getItem('rr-name') || '';
let ws = null;
let wsGen = 0;            // guards stale reconnect handlers after re-connect
let intentionalClose = false;
let fatalError = false;
let serverOffsetMs = 0;   // serverTime - localTime
let reconnectAttempt = 0;
let reconnectTimer = null;

/* ---------------------------------------------------------------- *
 *  Web Audio engine (unchanged)
 * ---------------------------------------------------------------- */
let audioCtx = null;
let currentBuffer = null;
let currentTrackUrl = null;
let srcNode = null;
let startedCtxTime = 0;   // AudioContext time when srcNode was started
let bufferOffsetAtStart = 0; // seconds into the buffer at start
let driftTimer = null;
let lastFlash = 0;
let audioReady = false;   // true once the AudioContext is running (user gesture given)
let loadToken = 0;        // supersedes stale track loads

async function ensureAudioCtx() {
  if (!audioCtx) {
    const Ctx = window.AudioContext || window.webkitAudioContext;
    audioCtx = new Ctx();
  }
  if (audioCtx.state === 'suspended') {
    try { await audioCtx.resume(); } catch {}
  }
  if (audioCtx.state === 'running') audioReady = true;
  return audioCtx;
}

async function loadTrack(url) {
  if (currentTrackUrl === url && currentBuffer) return;
  const token = ++loadToken;
  currentTrackUrl = url;
  currentBuffer = null;
  setTrackLoading(true);
  try {
    const resp = await fetch(url);
    if (!resp.ok) throw new Error('HTTP ' + resp.status);
    const ab = await resp.arrayBuffer();
    const buf = await audioCtx.decodeAudioData(ab);
    if (token !== loadToken) return; // a newer load superseded this one
    currentBuffer = buf;
  } catch (e) {
    if (token !== loadToken) return;
    currentTrackUrl = null;
    const npSub = $('#now-playing .np__sub');
    if (npSub) npSub.textContent = 'Couldn\u2019t load this audio — try another track.';
    toast('Could not load audio: ' + e.message);
  } finally {
    if (token === loadToken) setTrackLoading(false);
  }
}

function stopNode() {
  if (srcNode) {
    try { srcNode.stop(); } catch {}
    try { srcNode.disconnect(); } catch {}
    srcNode = null;
  }
}

function playAt(elapsedMs) {
  if (!currentBuffer) return;
  stopNode();
  const lead = 0.08; // 80ms lookahead lets every device fire on the same tick
  const when = audioCtx.currentTime + lead;
  const offsetSec = Math.max(0, elapsedMs / 1000);
  if (offsetSec >= currentBuffer.duration - 0.05) return; // track ended; server will advance
  srcNode = audioCtx.createBufferSource();
  srcNode.buffer = currentBuffer;
  srcNode.connect(audioCtx.destination);
  srcNode.start(when, offsetSec);
  startedCtxTime = when;
  bufferOffsetAtStart = offsetSec;
}

function stopPlayback() {
  stopNode();
  if (driftTimer) { clearInterval(driftTimer); driftTimer = null; }
}

function startDriftMonitor() {
  if (driftTimer) clearInterval(driftTimer);
  driftTimer = setInterval(() => {
    if (!station || !station.playing) return;
    const expectedMs = Math.max(0, Date.now() + serverOffsetMs - station.startedAtEpochMs);
    const actualMs = bufferOffsetAtStart * 1000 + (audioCtx.currentTime - startedCtxTime) * 1000;
    if (Math.abs(expectedMs - actualMs) > 150 && currentBuffer) {
      playAt(expectedMs); // re-align to the station clock
      flashSync();
    }
    updatePositionUI(expectedMs);
  }, 1000);
}

/* ---------------------------------------------------------------- *
 *  State application
 * ---------------------------------------------------------------- */
async function applyState(s) {
  if (!s) return;
  station = s;
  const current = s.queue[s.queueIndex] || null;
  renderQueue(s.queue, s.queueIndex);
  renderNowPlaying(current, s.playing, s.theme);
  renderStatus(s);

  // Station identity in the header (safe: textContent).
  const titleEl = $('#station-title');
  const themeEl = $('#station-theme');
  if (titleEl) titleEl.textContent = s.name;
  if (themeEl) themeEl.textContent = s.theme;

  if (!current) {
    stopPlayback();
    updatePositionUI(0);
    return;
  }

  const targetMs = s.playing
    ? elapsedAt(s.startedAtEpochMs, Date.now() + serverOffsetMs)
    : s.positionMs;

  await ensureAudioCtx();
  if (currentTrackUrl !== current.url) await loadTrack(current.url);

  if (s.playing) {
    if (!audioReady) {
      // Browser blocks audio until a user gesture — show the unmute overlay.
      const ov = $('#unmute-overlay');
      if (ov) ov.classList.remove('hidden');
      updatePositionUI(targetMs);
    } else {
      playAt(targetMs);
      startDriftMonitor();
      updatePositionUI(targetMs);
    }
  } else {
    const ov = $('#unmute-overlay');
    if (ov) ov.classList.add('hidden');
    stopPlayback();
    updatePositionUI(targetMs);
  }
}

/* ---------------------------------------------------------------- *
 *  Clock calibration (serverTime vs localTime) — unchanged
 * ---------------------------------------------------------------- */
function calibrate() {
  return new Promise((resolve) => {
    if (!ws || ws.readyState !== WebSocket.OPEN) return resolve();
    const t0 = Date.now();
    const onMsg = (e) => {
      let m; try { m = JSON.parse(e.data); } catch { return; }
      if (m.type === 'pong') {
        ws.removeEventListener('message', onMsg);
        serverOffsetMs = estimateOffset({ sendAt: t0, serverTime: m.serverTime, receiveAt: Date.now() });
        resolve();
      }
    };
    ws.addEventListener('message', onMsg);
    ws.send(JSON.stringify({ type: 'ping' }));
    setTimeout(() => { ws.removeEventListener('message', onMsg); resolve(); }, 2000);
  });
}

/* ---------------------------------------------------------------- *
 *  WebSocket: connect / reconnect with backoff (generation-guarded)
 * ---------------------------------------------------------------- */
function stopReconnect() {
  if (reconnectTimer) { clearTimeout(reconnectTimer); reconnectTimer = null; }
}

function connect(code) {
  stopReconnect();
  const gen = ++wsGen;
  intentionalClose = false;
  ws = new WebSocket(wsUrl(code));

  ws.onopen = async () => {
    if (gen !== wsGen) { try { ws.close(); } catch {} return; }
    reconnectAttempt = 0;
    setConn('connected');
    await calibrate();
    applyState(station); // if we already have state cached, re-align now
  };
  ws.onmessage = (e) => {
    let m; try { m = JSON.parse(e.data); } catch { return; }
    if (gen === wsGen) handleMessage(m);
  };
  ws.onclose = (e) => {
    if (gen !== wsGen) return; // superseded by a newer connection — do nothing
    // Keep playing! The station clock is absolute (server epoch), so the drift
    // monitor stays correct without the socket — playback survives the drop and
    // the next successful join re-seeks us to the station timeline.
    if (intentionalClose) {
      setConn('offline');
      return;
    }
    if (e && e.code === 1008) {
      // Policy rejection (origin not allowed, etc.) — retrying cannot help.
      fatalError = true;
      showStationError('This server rejected the connection (origin not allowed).');
      stopReconnect();
      setConn('offline');
      return;
    }
    setConn('reconnecting');
    if (fatalError) return; // e.g. station not found — do not retry forever
    const delay = Math.min(8000, 500 * Math.pow(2, reconnectAttempt++));
    reconnectTimer = setTimeout(() => connect(code), delay);
  };
  ws.onerror = () => { try { ws.close(); } catch {} };
}

function send(obj) {
  if (ws && ws.readyState === WebSocket.OPEN) ws.send(JSON.stringify(obj));
}

function handleMessage(m) {
  switch (m.type) {
    case 'welcome':
      myId = m.yourId;
      if (!myName) { myName = m.yourName; localStorage.setItem('rr-name', myName); }
      renderMembers(m.members);
      if (m.station) applyState(m.station);
      break;
    case 'state':
      applyState(m.station);
      break;
    case 'members':
      renderMembers(m.members);
      break;
    case 'trackAdded':
      if (m.queue) renderQueue(m.queue, station ? station.queueIndex : 0);
      break;
    case 'error':
      if (/station not found/i.test(m.message)) {
        // The station doesn't exist — stop trying and tell the user.
        fatalError = true;
        showStationError(m.message);
        stopReconnect();
        intentionalClose = true;
        try { if (ws) ws.close(); } catch {}
        setConn('offline');
      } else {
        toast(m.message);
      }
      break;
    case 'pong': /* handled by calibrate() */
      break;
  }
}

/* ---------------------------------------------------------------- *
 *  Routing: /station/<code> + legacy ?code=
 * ---------------------------------------------------------------- */
function enterStation(code, { replace = false } = {}) {
  code = String(code || '').toUpperCase();
  if (!CODE_RE.test(code)) {
    showStationError('That station code doesn\u2019t look right — it should be 6 letters/numbers, like AB12CD.');
    show('station');
    return;
  }
  stopReconnect();
  if (ws && ws.readyState === WebSocket.OPEN) {
    intentionalClose = true;
    try { ws.close(); } catch {}
  }
  wsGen++; // invalidate any pending reconnect of a previous connection
  if (replace) history.replaceState({ station: code }, '', '/station/' + code);
  else history.pushState({ station: code }, '', '/station/' + code);
  show('station');
  hideStationError();
  fatalError = false;
  $('#station-code').textContent = code;
  station = null;
  updateDocMeta(code);
  connect(code);
}

function leaveStation() {
  stopReconnect();
  stopPlayback();
  intentionalClose = true;
  wsGen++;
  if (ws) { try { ws.close(); } catch {} }
  ws = null;
  hideStationError();
  updateDocMeta(null);
  history.pushState({ station: null }, '', '/');
  show('home');
}

window.addEventListener('popstate', () => {
  const code = codeFromPath();
  if (code) {
    enterStation(code, { replace: true });
  } else {
    // Back/forward to home — disconnect cleanly.
    stopReconnect();
    stopPlayback();
    intentionalClose = true;
    wsGen++;
    if (ws) { try { ws.close(); } catch {} }
    ws = null;
    hideStationError();
    updateDocMeta(null);
    show('home');
  }
});

/* ---------------------------------------------------------------- *
 *  Landing: create / join
 * ---------------------------------------------------------------- */
async function createStation() {
  const name = $('#create-name').value.trim() || 'Untitled Station';
  const theme = $('#create-theme').value.trim() || 'Any vibe';
  try {
    const res = await fetch(api('/api/stations'), {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ name, theme }),
    });
    if (!res.ok) return toast('Could not create station (server error ' + res.status + '). Try again shortly.');
    const data = await res.json();
    enterStation(data.code);
  } catch {
    toast('Could not reach the server. Check your connection and try again.');
  }
}

function joinStation() {
  const code = $('#join-code').value.trim().toUpperCase();
  if (!CODE_RE.test(code)) return toast('That code does not look right (6 letters/numbers).');
  enterStation(code);
}

function saveName() {
  const name = $('#your-name').value.trim();
  if (name) { myName = name; localStorage.setItem('rr-name', name); }
  send({ type: 'hello', name: myName });
  toast('Name updated');
}

function pickTheme(chip) {
  $('#create-theme').value = chip.dataset.vibe;
}

/* ---------------------------------------------------------------- *
 *  Station controls
 * ---------------------------------------------------------------- */
function addTrack() {
  const url = $('#track-url').value.trim();
  const title = $('#track-title').value.trim();
  const artist = $('#track-artist').value.trim();
  if (!url) return toast('Paste a direct audio link first (mp3/ogg/m4a/webm/wav).');
  send({ type: 'addTrack', url, title, artist, vibe: station ? station.theme : '' });
  $('#track-url').value = ''; $('#track-title').value = ''; $('#track-artist').value = '';
}

function addCurated(url, title, artist, vibe) {
  send({ type: 'addTrack', url, title, artist, vibe });
  toast(`"${title}" added to the queue`);
}

/* ---------------------------------------------------------------- *
 *  Rendering (memoized where hot — state pushes arrive every second)
 * ---------------------------------------------------------------- */
let lastQueueSig = '';
function renderQueue(queue, index) {
  const sig = (queue || []).map((t) => t.id).join(',') + '#' + (index || 0);
  if (sig === lastQueueSig) return;
  lastQueueSig = sig;

  const list = $('#queue-list');
  const empty = $('#queue-empty');
  if (!queue || queue.length === 0) {
    list.innerHTML = '';
    if (empty) empty.classList.remove('hidden');
    return;
  }
  if (empty) empty.classList.add('hidden');
  list.innerHTML = queue.map((t, i) => `
    <li class="track ${i === index ? 'track--current' : ''}" data-id="${t.id}">
      <span class="track__idx">${i === index ? '▶' : String(i + 1).padStart(2, '0')}</span>
      <div class="track__meta">
        <span class="track__title">${esc(t.title)}</span>
        <span class="track__sub">${esc(t.artist)} · ${esc(t.vibe || '')}</span>
      </div>
      <button class="btn btn--ghost btn--sm" data-play="${t.id}" title="Play now">Play</button>
    </li>`).join('');

  list.querySelectorAll('[data-play]').forEach((btn) => {
    btn.addEventListener('click', () => send({ type: 'play', trackId: btn.dataset.play }));
  });
}

let lastNpSig = '';
function renderNowPlaying(current, playing, theme) {
  const sig = current ? `${current.title}|${current.artist}|${current.vibe || theme}|${playing}` : '';
  if (sig === lastNpSig) return;
  lastNpSig = sig;

  const np = $('#now-playing');
  if (!current) {
    np.querySelector('.np__title').textContent = 'Nothing on the air';
    np.querySelector('.np__sub').textContent = 'Add a track to start the vibe';
    np.querySelector('.np__elapsed').textContent = '--:--';
    $('#vinyl').classList.toggle('spin', false);
    $('#btn-play').disabled = true;
    $('#btn-next').disabled = true;
    $('#btn-prev').disabled = true;
    return;
  }
  np.querySelector('.np__title').textContent = current.title;
  np.querySelector('.np__sub').textContent = `${current.artist} — ${current.vibe || theme}`;
  $('#vinyl').classList.toggle('spin', playing);
  $('#btn-play').disabled = false;
  $('#btn-next').disabled = false;
  $('#btn-prev').disabled = false;
  $('#btn-play').innerHTML = playing ? '❚❚ Pause' : '▶ Play';
}

function updatePositionUI(ms) {
  const el = $('#elapsed');
  if (el) el.textContent = fmtTime(ms);
  const bar = $('#progress');
  if (bar && currentBuffer && currentBuffer.duration) {
    bar.style.width = Math.min(100, (ms / 1000 / currentBuffer.duration) * 100) + '%';
  }
}

function renderStatus(s) {
  const members = $('#member-count');
  if (members) members.textContent = `${(s && s.memberCount != null) ? s.memberCount : '—'} 👥`;
}

// Per-route document metadata (title + canonical). Uses the configured
// PUBLIC_ORIGIN when present, else the origin the user is actually on — never
// a hardcoded tunnel/dev URL.
function updateDocMeta(code) {
  const origin = RR_CONFIG.origin || location.origin;
  let canonical = document.querySelector('link[rel="canonical"]');
  if (!canonical) {
    canonical = document.createElement('link');
    canonical.rel = 'canonical';
    document.head.appendChild(canonical);
  }
  canonical.href = origin + (code ? '/station/' + code : '/');
  document.title = code
    ? `Station ${code} · RadioRang`
    : 'RadioRang — One Station, Any Vibe';
}

function renderMembers(members) {
  const list = $('#members-list');
  if (!list) return;
  if (!members || members.length === 0) { list.innerHTML = '<li class="member member--empty">No one else here yet — share the code!</li>'; return; }
  list.innerHTML = members.map((m) => `
    <li class="member${m.id === myId ? ' member--me' : ''}">
      <span class="member__dot"></span>${esc(m.name)}${m.id === myId ? ' <em>(you)</em>' : ''}
    </li>`).join('');
}

function setConn(state) {
  const pill = $('#conn-pill');
  if (!pill) return;
  pill.dataset.state = state;
  const labels = { connected: '● Live', reconnecting: '↻ Reconnecting…', offline: '○ Offline' };
  pill.textContent = labels[state] || state;
}

function setTrackLoading(on) {
  const el = $('#track-loading');
  if (el) el.classList.toggle('hidden', !on);
}

function flashSync() {
  const now = Date.now();
  if (now - lastFlash < 1500) return;
  lastFlash = now;
  const el = $('#sync-badge');
  if (!el) return;
  el.classList.remove('hidden');
  el.textContent = '⇄ Re-synced to station clock';
  setTimeout(() => el.classList.add('hidden'), 2000);
}

function showStationError(message) {
  const card = $('#station-error');
  const text = $('#station-error-text');
  if (text) text.textContent = message || 'This station could not be reached.';
  if (card) card.classList.remove('hidden');
}

function hideStationError() {
  const card = $('#station-error');
  if (card) card.classList.add('hidden');
}

function toast(msg) {
  const t = $('#toast');
  t.textContent = msg;
  t.classList.remove('hidden');
  clearTimeout(t._timer);
  t._timer = setTimeout(() => t.classList.add('hidden'), 3500);
}

/* ---------------------------------------------------------------- *
 *  Sounds of Azaadi shelf (platform links + official Spotify embeds)
 * ---------------------------------------------------------------- */
function renderAzaadi() {
  const list = $('#azaadi-list');
  if (!list) return;
  list.innerHTML = AZAADI.map((s) => {
    const actions = [];
    if (s.spotifyTrackId) {
      actions.push(`<a class="pl pl--spotify" href="https://open.spotify.com/track/${s.spotifyTrackId}" target="_blank" rel="noopener">▶ Spotify</a>`);
    }
    if (s.jiosaavn) {
      actions.push(`<a class="pl pl--jiosaavn" href="${esc(s.jiosaavn)}" target="_blank" rel="noopener">♪ JioSaavn</a>`);
    }
    if (s.gaana) {
      actions.push(`<a class="pl pl--gaana" href="${esc(s.gaana)}" target="_blank" rel="noopener">♫ Gaana</a>`);
    }
    const embed = s.spotifyTrackId
      ? `<iframe class="azaadi__embed" src="https://open.spotify.com/embed/track/${s.spotifyTrackId}?utm_source=generator&theme=0" width="100%" height="80" frameBorder="0" allow="autoplay; clipboard-write; encrypted-media; fullscreen; picture-in-picture" loading="lazy" title="${esc(s.title)} — listen on Spotify"></iframe>`
      : '';
    return `<article class="song">
      <div class="song__head">
        <div class="song__titles">
          <h3>${esc(s.title)}</h3>
          <p class="song__artist">${esc(s.artist)} · ${esc(s.year)}</p>
        </div>
        <span class="song__era">${esc(s.era)}</span>
      </div>
      <p class="song__context">${esc(s.context)}</p>
      <div class="song__actions">${actions.join('')}</div>
      ${embed}
    </article>`;
  }).join('');
}

/* ---------------------------------------------------------------- *
 *  Boot
 * ---------------------------------------------------------------- */
function esc(s) {
  return String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}
function fmtTime(ms) {
  const total = Math.floor((ms || 0) / 1000);
  return `${String(Math.floor(total / 60)).padStart(2, '0')}:${String(total % 60).padStart(2, '0')}`;
}

async function boot() {
  // your display name
  $('#your-name').value = myName;

  // wire up landing
  $('#btn-create').addEventListener('click', createStation);
  $('#btn-join').addEventListener('click', joinStation);
  $('#join-code').addEventListener('keydown', (e) => { if (e.key === 'Enter') joinStation(); });
  $('#btn-save-name').addEventListener('click', saveName);
  $$('.vibe-chip').forEach((c) => c.addEventListener('click', () => pickTheme(c)));

  // wire up station
  $('#btn-play').addEventListener('click', () => {
    const playing = station && station.playing;
    send({ type: playing ? 'pause' : 'play' });
  });
  $('#btn-next').addEventListener('click', () => send({ type: 'next' }));
  $('#btn-prev').addEventListener('click', () => send({ type: 'prev' }));
  $('#btn-bump').addEventListener('click', () => send({ type: 'bump', seconds: 10 }));
  $('#btn-copy').addEventListener('click', async () => {
    const code = $('#station-code').textContent;
    const link = `${location.origin}/station/${code}`;
    try {
      await navigator.clipboard.writeText(link);
      toast('Share link copied');
    } catch {
      toast('Link: ' + link);
    }
  });
  $('#btn-add-track').addEventListener('click', addTrack);
  $('#track-url').addEventListener('keydown', (e) => { if (e.key === 'Enter') addTrack(); });
  $('#btn-back').addEventListener('click', () => leaveStation());
  $('#station-error-back').addEventListener('click', () => leaveStation());

  // curated shelf — must never break the rest of the app if the server is down
  try {
    const res = await fetch(api('/api/tracks'));
    if (res.ok) {
      const tracks = await res.json();
      $('#curated-list').innerHTML = tracks.map((t) => `
        <button class="curated" data-url="${esc(t.url)}" data-title="${esc(t.title)}" data-artist="${esc(t.artist)}" data-vibe="${esc(t.vibe)}">
          <span class="curated__vibe">${esc(t.vibe)}</span>
          <span class="curated__title">${esc(t.title)}</span>
          <span class="curated__artist">${esc(t.artist)}</span>
        </button>`).join('');
      $$('.curated').forEach((b) => b.addEventListener('click', () => {
        addCurated(b.dataset.url, b.dataset.title, b.dataset.artist, b.dataset.vibe);
      }));
    } else {
      toast('Ready-made vibes unavailable (server unreachable) — you can still paste a direct audio link.');
    }
  } catch {
    toast('Ready-made vibes unavailable (server unreachable) — you can still paste a direct audio link.');
  }

  // Sounds of Azaadi shelf
  renderAzaadi();

  // route: /station/<code> (direct nav, refresh) or legacy ?code=
  let code = codeFromPath();
  if (!code) {
    const params = new URLSearchParams(location.search);
    code = (params.get('code') || '').toUpperCase();
  }
  if (code) {
    enterStation(code, { replace: codeFromPath() !== null });
  } else if (location.pathname.startsWith('/station/')) {
    // /station/<malformed-code> — explain the problem instead of silently
    // falling back to the home view.
    showStationError('That station code doesn\u2019t look right \u2014 it should be 6 letters/numbers, like AB12CD.');
    $('#station-code').textContent = '';
    show('station');
  } else {
    updateDocMeta(null);
    show('home');
  }

  // service worker
  if ('serviceWorker' in navigator) {
    navigator.serviceWorker.register('/sw.js').catch(() => {});
  }

  // presence heartbeat + keep clock honest
  setInterval(() => send({ type: 'ping' }), 15000);

  // unmute overlay: browsers need a gesture to start audio
  $('#btn-unmute').addEventListener('click', async () => {
    await ensureAudioCtx();
    $('#unmute-overlay').classList.add('hidden');
    if (station) applyState(station);
  });

  // Debug hook for e2e/console verification
  window.__rr = {
    get station() { return station; },
    get myId() { return myId; },
    get audioReady() { return audioReady; },
    get ctxTime() { return audioCtx ? audioCtx.currentTime : 0; },
    actualMs: () => (currentBuffer && srcNode)
      ? bufferOffsetAtStart * 1000 + (audioCtx.currentTime - startedCtxTime) * 1000
      : null,
    reconnectNow: () => { if (ws) { try { ws.close(); } catch {} } },
    get wsGen() { return wsGen; },
    get connState() { const p = $('#conn-pill'); return p ? p.dataset.state : null; },
  };
}

